/// Window/pane title for a plugin UI: the numeric id plus the plugin's file
/// stem, so several open plugin windows can be told apart.
pub(crate) fn plugin_ui_title(client: &impl EngineClient, plugin_id: u8) -> String {
    let name = client.with_plugins(|plugins| {
        plugins.get(&plugin_id).and_then(|p| {
            std::path::Path::new(p.path.as_ref())
                .file_stem()
                .map(|stem| stem.to_string_lossy().into_owned())
        })
    });
    match name {
        Some(name) => format!("Plugin UI #{plugin_id} · {name}"),
        None => format!("Plugin UI #{plugin_id}"),
    }
}

impl BlaulichtApp {
    /// Whether plugin `plugin_id` is an animation plugin, whose UI lives in
    /// the animation editor.
    fn is_animation_plugin(&self, plugin_id: u8) -> bool {
        self.client.with_plugin_runtime_kinds(|kinds| {
            matches!(
                kinds.get(&plugin_id),
                Some(blaulicht_engine::state::PluginRuntimeKind::Animation { .. })
            )
        })
    }

    /// Popups a plugin marked fullscreen: modal over the whole app, whether or
    /// not that plugin's UI is open. A plugin that is disabled or has crashed
    /// no longer ticks, so its last ops never change; they must not leave a
    /// modal up that nothing can close.
    pub(crate) fn render_plugin_fullscreen_popups(&mut self, ctx: &Context) {
        let plugin_ops: Vec<(u8, Vec<blaulicht_engine::ui_ops::WasmUiOp>)> =
            self.client.with_plugin_ui_ops(|ops| {
                ops.iter()
                    .filter(|(_, ops)| !fullscreen_popups(ops).is_empty())
                    .map(|(id, ops)| (*id, ops.clone()))
                    .collect()
            });

        for (plugin_id, ops) in plugin_ops {
            let running = self.client.with_plugins(|plugins| {
                plugins
                    .get(&plugin_id)
                    .is_some_and(|p| p.is_enabled() && !p.has_errored())
            });
            if !running || self.is_animation_plugin(plugin_id) {
                continue;
            }
            for (popup_id, start, end) in fullscreen_popups(&ops) {
                let client = &self.client;
                let tabs_selected = &mut self.view_state.plugin_tabs_selected;
                components::Dialog::new(
                    format!("plugin_popup::{plugin_id}::{popup_id}"),
                    egui::vec2(PLUGIN_POPUP_WIDTH, 160.0),
                )
                .with_backdrop()
                .show(ctx, |ui| {
                    render_popup_body(
                        ui,
                        &ops[..end],
                        start,
                        client,
                        plugin_id,
                        None,
                        tabs_selected,
                    );
                });
            }
        }
    }

    pub(crate) fn render_plugin_ui_contents(&mut self, ui: &mut egui::Ui, plugin_id: u8) {
        if self.is_animation_plugin(plugin_id) {
            ui.label("Animation plugin UI is available in the animation editor.");
            return;
        }
        let ops = self
            .client
            .with_plugin_ui_ops(|ops| ops.get(&plugin_id).cloned());

        if let Some(ops) = ops {
            let mut idx = 0usize;
            render_plugin_ops(
                ui,
                &ops,
                &mut idx,
                &self.client,
                plugin_id,
                None,
                &mut self.view_state.plugin_tabs_selected,
            );
        } else {
            ui.label("No UI generated by plugin yet.");
        }
    }

    pub fn render_plugin_ui(&mut self, ctx: &Context, canvas_screen_id: ScreenId) {
        let visibility_map = self.view_state.plugin_visibility.clone();
        // Copies of the ops of the windows open on this screen only.
        let ops_map: std::collections::HashMap<u8, Vec<blaulicht_engine::ui_ops::WasmUiOp>> =
            self.client.with_plugin_ui_ops(|ops| {
                visibility_map
                    .iter()
                    .filter(|(_, visibility)| {
                        visibility.open && visibility.screen_id == canvas_screen_id
                    })
                    .filter_map(|(id, _)| ops.get(id).map(|ops| (*id, ops.clone())))
                    .collect()
            });

        for (plugin_id, visibility) in visibility_map.iter() {
            let plugin_id = *plugin_id;
            if self.is_animation_plugin(plugin_id) {
                continue;
            }
            let mut is_open = visibility.open;
            if !is_open {
                continue;
            }

            if visibility.screen_id != canvas_screen_id {
                continue;
            }

            // The desktop draws an open plugin UI embedded in System ›
            // Plugins (086); only a popped-out one gets its own window.
            if self.layout.is_desktop()
                && canvas_screen_id == ScreenId::MAIN
                && !(cfg!(feature = "plugin-popout") && self.view_state.is_popped_out(plugin_id))
            {
                continue;
            }

            let title = plugin_ui_title(&self.client, plugin_id);
            let popped_out =
                cfg!(feature = "plugin-popout") && self.view_state.is_popped_out(plugin_id);
            let maximize_requested = popped_out && self.view_state.take_maximize_request(plugin_id);
            let client = &self.client;
            let tabs_selected = &mut self.view_state.plugin_tabs_selected;

            // The closures below only collect what the user did; it is applied
            // to the view state afterwards.
            let mut pop_toggled = false;
            let mut close_requested = false;

            if popped_out {
                let viewport_id = egui::ViewportId::from_hash_of(format!("plugin_{}", plugin_id));
                let ops = ops_map.get(&plugin_id);

                let mut viewport = egui::ViewportBuilder::default()
                    .with_title(title.clone())
                    .with_inner_size([800.0, 600.0])
                    .with_resizable(true);

                if maximize_requested {
                    viewport = viewport.with_maximized(true);
                }

                ctx.show_viewport_immediate(viewport_id, viewport, |ctx, _class| {
                    if maximize_requested {
                        ctx.send_viewport_cmd(egui::ViewportCommand::Maximized(true));
                    }

                    egui::CentralPanel::default().show(ctx, |ui| {
                        ui.horizontal(|ui| {
                            if plugin_action(ui, "Pop in", true) {
                                pop_toggled = true;
                            }
                        });
                        ui.separator();

                        egui::ScrollArea::both()
                            .auto_shrink([false, false])
                            .stick_to_bottom(false)
                            .show(ui, |ui| {
                                if let Some(ops) = ops {
                                    let mut idx = 0usize;
                                    render_plugin_ops(
                                        ui,
                                        ops,
                                        &mut idx,
                                        client,
                                        plugin_id,
                                        None,
                                        tabs_selected,
                                    );
                                } else {
                                    ui.label("No UI generated by plugin yet.");
                                }
                            });
                    });

                    if ctx.input(|i| i.viewport().close_requested()) {
                        close_requested = true;
                    }
                });

                if pop_toggled {
                    self.view_state.set_popped_out(plugin_id, false);
                }
            } else {
                egui::Window::new(&title)
                    .open(&mut is_open)
                    .default_size([560.0, 400.0])
                    .resizable(true)
                    .show(ctx, |ui| {
                        if cfg!(feature = "plugin-popout") {
                            ui.horizontal(|ui| {
                                if plugin_action(ui, "Pop out", true) {
                                    pop_toggled = true;
                                }
                            });
                            ui.separator();
                        }

                        egui::ScrollArea::both()
                            .auto_shrink([false, false])
                            .stick_to_bottom(false)
                            .show(ui, |ui| {
                                if let Some(ops) = ops_map.get(&plugin_id) {
                                    let mut idx = 0usize;
                                    render_plugin_ops(
                                        ui,
                                        ops,
                                        &mut idx,
                                        client,
                                        plugin_id,
                                        None,
                                        tabs_selected,
                                    );
                                } else {
                                    ui.label("No UI generated by plugin yet.");
                                }
                            });
                    });

                if pop_toggled {
                    self.view_state.set_popped_out(plugin_id, true);
                }
                close_requested |= !is_open;
            }

            if close_requested {
                self.view_state.set_plugin_open(plugin_id, false);
            }
        }
    }
}

/// Width of a plugin popup, as far as the space it covers allows.
const PLUGIN_POPUP_WIDTH: f32 = 420.0;

/// Index of the `EndPopup` closing the popup whose body starts at `start`
/// (`ops.len()` if the plugin never closed it).
fn popup_end(ops: &[blaulicht_engine::ui_ops::WasmUiOp], start: usize) -> usize {
    use blaulicht_engine::ui_ops::WasmUiOp as Op;
    let mut depth = 1usize;
    for (i, op) in ops.iter().enumerate().skip(start) {
        match op {
            Op::BeginPopup { .. } => depth += 1,
            Op::EndPopup => {
                depth -= 1;
                if depth == 0 {
                    return i;
                }
            }
            _ => {}
        }
    }
    ops.len()
}

/// The `(id, body start, body end)` of each outermost fullscreen popup, in any
/// tab or container: fullscreen popups show no matter what.
fn fullscreen_popups(ops: &[blaulicht_engine::ui_ops::WasmUiOp]) -> Vec<(u8, usize, usize)> {
    use blaulicht_engine::ui_ops::WasmUiOp as Op;
    let mut popups = Vec::new();
    let mut i = 0;
    while i < ops.len() {
        if let Op::BeginPopup { id, fullscreen } = ops[i] {
            let end = popup_end(ops, i + 1);
            if fullscreen {
                popups.push((id, i + 1, end));
            }
            i = end;
        }
        i += 1;
    }
    popups
}

/// Renders a popup body; `ops` ends where the body does.
fn render_popup_body(
    ui: &mut egui::Ui,
    ops: &[blaulicht_engine::ui_ops::WasmUiOp],
    start: usize,
    client: &impl EngineClient,
    plugin_id: u8,
    animation_instance: Option<u64>,
    tabs_selected: &mut PluginTabSelections,
) {
    let mut idx = start;
    while idx < ops.len() {
        render_plugin_ops(
            ui,
            ops,
            &mut idx,
            client,
            plugin_id,
            animation_instance,
            tabs_selected,
        );
    }
}

/// A popup over the plugin's UI only: its backdrop covers what `ui` shows and
/// leaves the rest of the app usable. It is drawn from the plugin UI's own
/// rendering, so it disappears along with that.
#[allow(clippy::too_many_arguments)]
fn render_plugin_window_popup(
    ui: &mut egui::Ui,
    ops: &[blaulicht_engine::ui_ops::WasmUiOp],
    start: usize,
    popup_id: u8,
    client: &impl EngineClient,
    plugin_id: u8,
    animation_instance: Option<u64>,
    tabs_selected: &mut PluginTabSelections,
) {
    let ctx = ui.ctx().clone();
    let covered = ui.clip_rect();
    let id = egui::Id::new(("plugin_popup", plugin_id, animation_instance, popup_id));

    let backdrop = egui::Area::new(id.with("backdrop"))
        .order(egui::Order::Foreground)
        .fixed_pos(covered.min)
        .interactable(true)
        .show(&ctx, |ui| {
            // Swallows clicks, so the widgets underneath can't be used.
            ui.allocate_rect(
                egui::Rect::from_min_size(covered.min, covered.size()),
                egui::Sense::click(),
            );
            ui.painter()
                .rect_filled(covered, 0.0, egui::Color32::from_black_alpha(180));
        })
        .response
        .layer_id;
    let window_layer = egui::LayerId::new(egui::Order::Foreground, id);
    ctx.memory_mut(|mem| {
        let areas = mem.areas_mut();
        areas.move_to_top(backdrop);
        areas.move_to_top(window_layer);
    });

    let width = PLUGIN_POPUP_WIDTH.min((covered.width() - 24.0).max(1.0));
    egui::Window::new("plugin_popup")
        .id(id)
        .title_bar(false)
        .collapsible(false)
        .resizable(false)
        .order(egui::Order::Foreground)
        .pivot(egui::Align2::CENTER_CENTER)
        .fixed_pos(covered.center())
        .fixed_size(egui::vec2(width, 0.0))
        .frame(components::dialog_frame(&ctx))
        .show(&ctx, |ui| {
            ui.vertical_centered(|ui| {
                render_popup_body(
                    ui,
                    ops,
                    start,
                    client,
                    plugin_id,
                    animation_instance,
                    tabs_selected,
                );
            });
        });
}

/// Use the application's button geometry, expanding labels before truncating.
fn plugin_button_size(ui: &egui::Ui, label: &str) -> components::ButtonSize {
    let size = components::ButtonSize::Medium;
    let text_width = ui
        .painter()
        .layout_no_wrap(
            label.to_owned(),
            egui::FontId::proportional(size.dim().1),
            ui.visuals().text_color(),
        )
        .size()
        .x;
    size.with_width(
        (text_width + 24.0)
            .max(size.dim().0.x)
            .min(ui.max_rect().width().max(90.0)),
    )
}

fn plugin_action(ui: &mut egui::Ui, label: &str, enabled: bool) -> bool {
    let size = plugin_button_size(ui, label);
    components::action_button(ui, enabled, label, size, None)
}

/// Show a text field whose committed value comes from the plugin a tick late.
/// While the field has focus the text typed so far is kept in egui memory so
/// the plugin's stale echo cannot overwrite it mid-keystroke; once focus is
/// lost the plugin's value is shown again. Returns the new text when edited.
fn plugin_text_edit(
    ui: &mut egui::Ui,
    plugin_id: u8,
    animation_instance: Option<u64>,
    id: u8,
    text: &str,
    multiline: bool,
) -> Option<String> {
    let edit_id = ui.make_persistent_id((
        "plugin_text_edit",
        plugin_id,
        animation_instance,
        id,
        multiline,
    ));
    let has_focus = ui.memory(|m| m.has_focus(edit_id));
    let mut s = if has_focus {
        ui.data_mut(|d| {
            d.get_temp::<String>(edit_id)
                .unwrap_or_else(|| text.to_owned())
        })
    } else {
        text.to_owned()
    };

    let response = if multiline {
        ui.add(
            egui::TextEdit::multiline(&mut s)
                .id(edit_id)
                .desired_rows(3)
                .desired_width(300.0),
        )
    } else {
        ui.add(egui::TextEdit::singleline(&mut s).id(edit_id))
    };

    ui.data_mut(|d| d.insert_temp(edit_id, s.clone()));
    response.changed().then_some(s)
}

/// Render `ops` starting at `idx` until the ops run out or a matching `End*`
/// op returns from the current nesting level. Callers bound nested content by
/// passing a shorter slice (`&ops[..end]`); indexes stay relative to the full
/// op list.
pub(crate) fn render_plugin_ops(
    ui: &mut egui::Ui,
    ops: &[blaulicht_engine::ui_ops::WasmUiOp],
    idx: &mut usize,
    client: &impl EngineClient,
    plugin_id: u8,
    animation_instance: Option<u64>,
    tabs_selected: &mut PluginTabSelections,
) {
    use blaulicht_engine::ui_ops::WasmUiOp as Op;
    let route_event = |event| match animation_instance {
        Some(instance) => ControlEvent::AnimationPluginUi(event, plugin_id, instance),
        None => ControlEvent::PluginUi(event, plugin_id),
    };
    while *idx < ops.len() {
        match &ops[*idx] {
            Op::Label(text) => {
                ui.label(text);
                *idx += 1;
            }
            Op::LabelStyled {
                text,
                size,
                monospace,
            } => {
                let mut rich = egui::RichText::new(text).size(*size as f32);
                if *monospace {
                    rich = rich.monospace();
                }
                ui.label(rich);
                *idx += 1;
            }
            Op::SetMaxWidth { width } => {
                if *width > 0 {
                    ui.set_max_width(*width as f32);
                }
                *idx += 1;
            }
            Op::SetMinWidth { width } => {
                if *width >= 0 {
                    ui.set_min_width(*width as f32);
                }
                *idx += 1;
            }
            Op::Separator => {
                ui.separator();
                *idx += 1;
            }
            Op::Button { label, id } => {
                if plugin_action(ui, label, true) {
                    let evt = route_event(PluginUiEvent::Button { id: *id });
                    client.send(ControlEventMessage::new(EventOriginator::Web, evt));
                }
                *idx += 1;
            }
            Op::ButtonStyled { label, id, enabled } => {
                let clicked = plugin_action(ui, label, *enabled);
                if *enabled && clicked {
                    let evt = route_event(PluginUiEvent::Button { id: *id });
                    client.send(ControlEventMessage::new(EventOriginator::Web, evt));
                }
                *idx += 1;
            }
            Op::ComboBox {
                label,
                id,
                options,
                selected,
            } => {
                let combo_id = ui.make_persistent_id(format!("plugin_combo_{}_{}", plugin_id, id));
                let mut current = *selected;
                let mut changed = false;
                let selected_text = options
                    .get(current as usize)
                    .map(|s| s.as_str())
                    .unwrap_or("<none>");
                ui.horizontal(|ui| {
                    if !label.is_empty() {
                        ui.label(label);
                    }
                    if dropdown::is_desktop(ui) {
                        let list = dropdown::items(options);
                        if let Some(i) = dropdown::select(
                            ui,
                            combo_id,
                            &list,
                            Some(current as usize),
                            selected_text,
                            None,
                        ) {
                            if i as u8 != current {
                                current = i as u8;
                                changed = true;
                            }
                        }
                    } else {
                        dropdown::kiosk_combo(ui, combo_id, None, selected_text, |ui| {
                            for (idx_opt, label) in options.iter().enumerate() {
                                if ui
                                    .selectable_value(&mut current, idx_opt as u8, label)
                                    .changed()
                                {
                                    changed = true;
                                }
                            }
                        });
                    }
                });

                if changed {
                    let evt = route_event(PluginUiEvent::ComboBox {
                        id: *id,
                        selected: current,
                    });
                    client.send(ControlEventMessage::new(EventOriginator::Web, evt));
                }
                *idx += 1;
            }
            Op::Checkbox { label, id, checked } => {
                let mut c = *checked;
                if ui.checkbox(&mut c, label).changed() {
                    let evt = route_event(PluginUiEvent::Checkbox {
                        id: *id,
                        checked: c,
                    });
                    client.send(ControlEventMessage::new(EventOriginator::Web, evt));
                }
                *idx += 1;
            }
            Op::Switch { label, id, value } => {
                let mut state = *value;
                let mut widget = components::Switch::new(&mut state);
                if !label.is_empty() {
                    widget = widget.with_label(label.clone());
                }

                if ui.add(widget).changed() {
                    let evt = route_event(PluginUiEvent::Switch {
                        id: *id,
                        value: state,
                    });
                    client.send(ControlEventMessage::new(EventOriginator::Web, evt));
                }

                *idx += 1;
            }
            Op::Slider {
                label,
                id,
                min,
                max,
                value,
            } => {
                let mut v = *value;
                if ui
                    .add(egui::Slider::new(&mut v, (*min)..=(*max)).text(label))
                    .changed()
                {
                    let evt = route_event(PluginUiEvent::Slider { id: *id, value: v });
                    client.send(ControlEventMessage::new(EventOriginator::Web, evt));
                }
                *idx += 1;
            }
            Op::HFader {
                label,
                id,
                min,
                max,
                value,
            } => {
                let mut current = *value as f32;
                let mut widget =
                    components::HFader::new(&mut current, (*min as f32)..=(*max as f32));
                if !label.is_empty() {
                    widget = widget.with_label(label.clone());
                }

                if ui.add(widget).changed() {
                    let new_value = current.round().clamp(*min as f32, *max as f32) as u8;
                    let evt = route_event(PluginUiEvent::HFader {
                        id: *id,
                        value: new_value,
                    });
                    client.send(ControlEventMessage::new(EventOriginator::Web, evt));
                }

                *idx += 1;
            }
            Op::TextEdit { label, id, text } => {
                let response = ui.horizontal(|ui| {
                    if !label.is_empty() {
                        ui.label(label);
                    }
                    plugin_text_edit(ui, plugin_id, animation_instance, *id, text, false)
                });
                if let Some(text) = response.inner {
                    let evt = route_event(PluginUiEvent::Text { id: *id, text });
                    client.send(ControlEventMessage::new(EventOriginator::Web, evt));
                }
                *idx += 1;
            }
            Op::TextEditMultiline { label, id, text } => {
                if !label.is_empty() {
                    ui.label(label);
                }
                if let Some(text) =
                    plugin_text_edit(ui, plugin_id, animation_instance, *id, text, true)
                {
                    let evt = route_event(PluginUiEvent::Text { id: *id, text });
                    client.send(ControlEventMessage::new(EventOriginator::Web, evt));
                }
                *idx += 1;
            }
            Op::ColorPicker { id, r, g, b, a } => {
                let mut color = egui::Color32::from_rgba_unmultiplied(*r, *g, *b, *a);
                if ui.color_edit_button_srgba(&mut color).changed() {
                    let [r, g, b, a] = color.to_srgba_unmultiplied();
                    let evt = route_event(PluginUiEvent::Color {
                        id: *id,
                        r,
                        g,
                        b,
                        a,
                    });
                    client.send(ControlEventMessage::new(EventOriginator::Web, evt));
                }
                *idx += 1;
            }
            Op::BeginFrame { id: _ } => {
                *idx += 1;
                ui.group(|ui| {
                    render_plugin_ops(
                        ui,
                        ops,
                        idx,
                        client,
                        plugin_id,
                        animation_instance,
                        tabs_selected,
                    );
                });
            }
            Op::BeginFrameStyled {
                id: _,
                title,
                pad_x,
                pad_y,
                margin_x,
                margin_y,
            } => {
                *idx += 1;
                egui::Frame::group(ui.style())
                    .inner_margin(egui::Margin::symmetric(
                        (*pad_x).clamp(0, 127) as i8,
                        (*pad_y).clamp(0, 127) as i8,
                    ))
                    .outer_margin(egui::Margin::symmetric(
                        (*margin_x).clamp(0, 127) as i8,
                        (*margin_y).clamp(0, 127) as i8,
                    ))
                    .show(ui, |ui| {
                        ui.vertical(|ui| {
                            if !title.is_empty() {
                                ui.label(egui::RichText::new(title).strong());
                                ui.separator();
                            }
                            render_plugin_ops(
                                ui,
                                ops,
                                idx,
                                client,
                                plugin_id,
                                animation_instance,
                                tabs_selected,
                            );
                        });
                    });
            }
            Op::BeginFrameStyledBorder {
                id: _,
                title,
                pad_x,
                pad_y,
                margin_x,
                margin_y,
                border_r,
                border_g,
                border_b,
                border_a,
                border_thickness,
            } => {
                *idx += 1;
                let stroke = egui::Stroke::new(
                    (*border_thickness).max(0) as f32,
                    egui::Color32::from_rgba_unmultiplied(
                        *border_r, *border_g, *border_b, *border_a,
                    ),
                );
                egui::Frame::group(ui.style())
                    .stroke(stroke)
                    .inner_margin(egui::Margin::symmetric(
                        (*pad_x).clamp(0, 127) as i8,
                        (*pad_y).clamp(0, 127) as i8,
                    ))
                    .outer_margin(egui::Margin::symmetric(
                        (*margin_x).clamp(0, 127) as i8,
                        (*margin_y).clamp(0, 127) as i8,
                    ))
                    .show(ui, |ui| {
                        ui.vertical(|ui| {
                            if !title.is_empty() {
                                ui.label(egui::RichText::new(title).strong());
                                ui.separator();
                            }
                            render_plugin_ops(
                                ui,
                                ops,
                                idx,
                                client,
                                plugin_id,
                                animation_instance,
                                tabs_selected,
                            );
                        });
                    });
            }
            Op::EndFrame => {
                *idx += 1;
                return;
            }
            Op::BeginCollapsing {
                id,
                title,
                default_open,
            } => {
                *idx += 1;
                let response = egui::CollapsingHeader::new(title)
                    .id_salt(("plugin_collapsing", plugin_id, animation_instance, *id))
                    .default_open(*default_open)
                    .show(ui, |ui| {
                        render_plugin_ops(
                            ui,
                            ops,
                            idx,
                            client,
                            plugin_id,
                            animation_instance,
                            tabs_selected,
                        );
                    });
                if response.body_returned.is_none() {
                    // Collapsed: egui skipped the body, so its ops are still
                    // unconsumed. Skip to the matching EndCollapsing, or the
                    // hidden content would render outside the header and its
                    // EndCollapsing would end the enclosing container early.
                    let mut depth = 1usize;
                    while *idx < ops.len() && depth > 0 {
                        match ops[*idx] {
                            Op::BeginCollapsing { .. } => depth += 1,
                            Op::EndCollapsing => depth -= 1,
                            _ => {}
                        }
                        *idx += 1;
                    }
                }
            }
            Op::EndCollapsing => {
                *idx += 1;
                return;
            }
            Op::BeginTabs { id } => {
                // Collect tabs metadata: (tab id, title, content start, content end).
                *idx += 1;
                let mut tabs: Vec<(u8, String, usize, usize)> = Vec::new();
                let mut scan = *idx;
                let mut end_tabs = ops.len();
                while scan < ops.len() {
                    match &ops[scan] {
                        Op::BeginTab {
                            tabs_id,
                            tab_id,
                            title,
                        } if tabs_id == id => {
                            let tab_start = scan + 1;
                            scan += 1;
                            let mut depth = 1;
                            while scan < ops.len() && depth > 0 {
                                match &ops[scan] {
                                    Op::BeginTab { .. } => depth += 1,
                                    Op::EndTab => depth -= 1,
                                    _ => {}
                                }
                                scan += 1;
                            }
                            // `scan` is just past this tab's EndTab.
                            let tab_end = scan.saturating_sub(1).max(tab_start);
                            tabs.push((*tab_id, title.clone(), tab_start, tab_end));
                        }
                        Op::EndTabs => {
                            end_tabs = scan;
                            break;
                        }
                        _ => scan += 1,
                    }
                }

                // Current selection, keyed per plugin so two plugins using the
                // same tabs id do not share one selection. Frontend view state;
                // the plugin learns about changes via `TabChanged`.
                let key = (plugin_id, *id);
                let default_tab = tabs.first().map(|t| t.0).unwrap_or(0);
                let mut current = *tabs_selected.entry(key).or_insert(default_tab);
                if !tabs.iter().any(|(tid, _, _, _)| *tid == current) {
                    current = default_tab;
                }

                // Tab header; wraps so many tabs stay reachable in a narrow window.
                let mut selection_changed = false;
                ui.horizontal_wrapped(|ui| {
                    for (tab_id, title, _, _) in &tabs {
                        let size = plugin_button_size(ui, title);
                        let clicked = components::button(ui, current == *tab_id, title, size);
                        if clicked && current != *tab_id {
                            current = *tab_id;
                            selection_changed = true;
                        }
                    }
                });

                ui.separator();

                if selection_changed {
                    tabs_selected.insert(key, current);
                    let evt = route_event(PluginUiEvent::TabChanged {
                        tabs_id: *id,
                        tab_id: current,
                    });
                    client.send(ControlEventMessage::new(EventOriginator::Web, evt));
                }

                // Render only the selected tab's content, bounded to its EndTab.
                if let Some((_, _, s, e)) = tabs.iter().find(|(tid, _, _, _)| *tid == current) {
                    let mut inner_idx = *s;
                    let bounded = &ops[..*e];
                    while inner_idx < *e {
                        render_plugin_ops(
                            ui,
                            bounded,
                            &mut inner_idx,
                            client,
                            plugin_id,
                            animation_instance,
                            tabs_selected,
                        );
                    }
                }

                // Continue after this group's EndTabs.
                *idx = (end_tabs + 1).min(ops.len());
            }
            Op::BeginTab { .. } | Op::EndTab | Op::EndTabs => {
                // Should be handled in BeginTabs
                *idx += 1;
            }
            Op::BeginPopup { id, fullscreen } => {
                let start = *idx + 1;
                let end = popup_end(ops, start);
                // Fullscreen ones belong to `render_plugin_fullscreen_popups`.
                if !*fullscreen {
                    render_plugin_window_popup(
                        ui,
                        &ops[..end],
                        start,
                        *id,
                        client,
                        plugin_id,
                        animation_instance,
                        tabs_selected,
                    );
                }
                *idx = (end + 1).min(ops.len());
            }
            Op::EndPopup => {
                // Should be handled in BeginPopup
                *idx += 1;
            }
            Op::ProgressBar { permille, text } => {
                let progress = (*permille).clamp(0, 1000) as f32 / 1000.0;
                BlaulichtApp::draw_progress_bar(ui, progress, 18.0, text);
                *idx += 1;
            }
            Op::BeginVertical => {
                *idx += 1;
                ui.vertical(|ui| {
                    render_plugin_ops(
                        ui,
                        ops,
                        idx,
                        client,
                        plugin_id,
                        animation_instance,
                        tabs_selected,
                    );
                });
            }
            Op::EndVertical => {
                *idx += 1;
                return;
            }
            Op::BeginHorizontal => {
                *idx += 1;
                // Wrap so rows of buttons stay reachable on the 800x480 panel
                // instead of running past the window edge.
                ui.horizontal_wrapped(|ui| {
                    render_plugin_ops(
                        ui,
                        ops,
                        idx,
                        client,
                        plugin_id,
                        animation_instance,
                        tabs_selected,
                    );
                });
            }
            Op::EndHorizontal => {
                *idx += 1;
                return;
            }
            Op::PainterBegin { id, width, height } if *width <= 0 || *height <= 0 => {
                // Degenerate canvas: skip its drawing ops instead of dividing by zero.
                *idx += 1;
                while *idx < ops.len() && !matches!(ops[*idx], Op::PainterEnd) {
                    *idx += 1;
                }
                *idx = (*idx + 1).min(ops.len());
                let _ = id;
            }
            Op::PainterBegin { id, width, height } => {
                *idx += 1;
                // Keep the requested aspect ratio, but fit the canvas to the pane.
                // Pointer coordinates below are converted back to plugin coordinates.
                let canvas_width = ui.available_width().max(1.0).min(*width as f32);
                let scaled_size =
                    egui::vec2(canvas_width, canvas_width * *height as f32 / *width as f32);
                let (rect, resp) =
                    ui.allocate_exact_size(scaled_size, egui::Sense::click_and_drag());
                tracing::debug!("PainterBegin: allocated rect={:?}", rect);

                let scale_x = *width as f32 / scaled_size.x;
                let scale_y = *height as f32 / scaled_size.y;

                if resp.clicked() {
                    if let Some(pos) = resp.interact_pointer_pos() {
                        let local_pos = pos - rect.min;
                        let evt = route_event(PluginUiEvent::CanvasClick {
                            id: *id,
                            x: (local_pos.x * scale_x) as i32,
                            y: (local_pos.y * scale_y) as i32,
                        });
                        client.send(ControlEventMessage::new(EventOriginator::Web, evt));
                    }
                }

                if resp.drag_started() {
                    if let Some(pos) = resp.interact_pointer_pos() {
                        let origin = pos - resp.total_drag_delta().unwrap_or_default() - rect.min;
                        client.send(ControlEventMessage::new(
                            EventOriginator::Web,
                            route_event(PluginUiEvent::CanvasDragStart {
                                id: *id,
                                x: (origin.x * scale_x) as i32,
                                y: (origin.y * scale_y) as i32,
                            }),
                        ));
                    }
                }
                if resp.drag_stopped() {
                    if let Some(pos) = resp.interact_pointer_pos() {
                        let local = pos - rect.min;
                        client.send(ControlEventMessage::new(
                            EventOriginator::Web,
                            route_event(PluginUiEvent::CanvasDragEnd {
                                id: *id,
                                x: (local.x * scale_x) as i32,
                                y: (local.y * scale_y) as i32,
                            }),
                        ));
                    }
                }
                if resp.dragged() {
                    if let Some(pos) = resp.interact_pointer_pos() {
                        let local_pos = pos - rect.min;
                        let delta = resp.drag_delta();
                        let evt = route_event(PluginUiEvent::CanvasDrag {
                            id: *id,
                            x: (local_pos.x * scale_x) as i32,
                            y: (local_pos.y * scale_y) as i32,
                            dx: (delta.x * scale_x) as i32,
                            dy: (delta.y * scale_y) as i32,
                        });
                        client.send(ControlEventMessage::new(EventOriginator::Web, evt));
                    }
                }

                let multi_touch = ui.input(|i| i.multi_touch());
                if let Some(zoom_delta) = multi_touch {
                    let zoom = zoom_delta.zoom_delta;
                    if zoom != 1.0 {
                        if let Some(pos) = resp.hover_pos() {
                            let local_pos = pos - rect.min;
                            let evt = route_event(PluginUiEvent::CanvasPinch {
                                id: *id,
                                x: (local_pos.x * scale_x) as i32,
                                y: (local_pos.y * scale_y) as i32,
                                delta: zoom - 1.0,
                            });
                            client.send(ControlEventMessage::new(EventOriginator::Web, evt));
                        }
                    }
                }

                let painter = ui.painter_at(rect);
                let render_scale_x = scaled_size.x / *width as f32;
                let render_scale_y = scaled_size.y / *height as f32;

                while *idx < ops.len() {
                    match &ops[*idx] {
                        Op::PainterRect {
                            x,
                            y,
                            w,
                            h,
                            r,
                            g,
                            b,
                            a,
                        } => {
                            let color = egui::Color32::from_rgba_unmultiplied(*r, *g, *b, *a);
                            let rct = egui::Rect::from_min_size(
                                rect.min
                                    + egui::vec2(
                                        *x as f32 * render_scale_x,
                                        *y as f32 * render_scale_y,
                                    ),
                                egui::vec2(*w as f32 * render_scale_x, *h as f32 * render_scale_y),
                            );
                            painter.rect_filled(rct, 0.0, color);
                            *idx += 1;
                        }
                        Op::PainterCircle {
                            x,
                            y,
                            radius,
                            r,
                            g,
                            b,
                            a,
                        } => {
                            let color = egui::Color32::from_rgba_unmultiplied(*r, *g, *b, *a);
                            painter.circle_filled(
                                rect.min
                                    + egui::vec2(
                                        *x as f32 * render_scale_x,
                                        *y as f32 * render_scale_y,
                                    ),
                                *radius as f32 * render_scale_x.min(render_scale_y),
                                color,
                            );
                            *idx += 1;
                        }
                        Op::PainterLine {
                            x1,
                            y1,
                            x2,
                            y2,
                            r,
                            g,
                            b,
                            a,
                            thickness,
                        } => {
                            let color = egui::Color32::from_rgba_unmultiplied(*r, *g, *b, *a);
                            painter.line_segment(
                                [
                                    rect.min
                                        + egui::vec2(
                                            *x1 as f32 * render_scale_x,
                                            *y1 as f32 * render_scale_y,
                                        ),
                                    rect.min
                                        + egui::vec2(
                                            *x2 as f32 * render_scale_x,
                                            *y2 as f32 * render_scale_y,
                                        ),
                                ],
                                egui::Stroke::new((*thickness).max(1) as f32, color),
                            );
                            *idx += 1;
                        }
                        Op::PainterText {
                            x,
                            y,
                            size,
                            r,
                            g,
                            b,
                            a,
                            text,
                        } => {
                            let color = egui::Color32::from_rgba_unmultiplied(*r, *g, *b, *a);
                            painter.text(
                                rect.min
                                    + egui::vec2(
                                        *x as f32 * render_scale_x,
                                        *y as f32 * render_scale_y,
                                    ),
                                egui::Align2::LEFT_TOP,
                                text,
                                egui::FontId::proportional(
                                    (*size).max(8) as f32 * render_scale_x.min(render_scale_y),
                                ),
                                color,
                            );
                            *idx += 1;
                        }
                        Op::PainterEnd => {
                            *idx += 1;
                            break;
                        }
                        Op::PainterRectStroke {
                            x,
                            y,
                            w,
                            h,
                            r,
                            g,
                            b,
                            a,
                            thickness,
                        } => {
                            let color = egui::Color32::from_rgba_unmultiplied(*r, *g, *b, *a);
                            let rct = egui::Rect::from_min_size(
                                rect.min
                                    + egui::vec2(
                                        *x as f32 * render_scale_x,
                                        *y as f32 * render_scale_y,
                                    ),
                                egui::vec2(*w as f32 * render_scale_x, *h as f32 * render_scale_y),
                            );
                            painter.rect_stroke(
                                rct,
                                0.0,
                                egui::Stroke::new((*thickness).max(1) as f32, color),
                                egui::StrokeKind::Middle,
                            );
                            *idx += 1;
                        }
                        Op::PainterCircleStroke {
                            x,
                            y,
                            radius,
                            r,
                            g,
                            b,
                            a,
                            thickness,
                        } => {
                            let color = egui::Color32::from_rgba_unmultiplied(*r, *g, *b, *a);
                            painter.circle_stroke(
                                rect.min
                                    + egui::vec2(
                                        *x as f32 * render_scale_x,
                                        *y as f32 * render_scale_y,
                                    ),
                                *radius as f32 * render_scale_x.min(render_scale_y),
                                egui::Stroke::new((*thickness).max(1) as f32, color),
                            );
                            *idx += 1;
                        }
                        Op::PainterCubicBezier {
                            x1,
                            y1,
                            cx1,
                            cy1,
                            cx2,
                            cy2,
                            x2,
                            y2,
                            r,
                            g,
                            b,
                            a,
                            thickness,
                        } => {
                            let color = egui::Color32::from_rgba_unmultiplied(*r, *g, *b, *a);
                            let shape = egui::epaint::CubicBezierShape {
                                points: [
                                    rect.min
                                        + egui::vec2(
                                            *x1 as f32 * render_scale_x,
                                            *y1 as f32 * render_scale_y,
                                        ),
                                    rect.min
                                        + egui::vec2(
                                            *cx1 as f32 * render_scale_x,
                                            *cy1 as f32 * render_scale_y,
                                        ),
                                    rect.min
                                        + egui::vec2(
                                            *cx2 as f32 * render_scale_x,
                                            *cy2 as f32 * render_scale_y,
                                        ),
                                    rect.min
                                        + egui::vec2(
                                            *x2 as f32 * render_scale_x,
                                            *y2 as f32 * render_scale_y,
                                        ),
                                ],
                                closed: false,
                                fill: egui::Color32::TRANSPARENT,
                                stroke: egui::epaint::PathStroke::new(
                                    (*thickness).max(1) as f32,
                                    color,
                                ),
                            };
                            painter.add(shape);
                            *idx += 1;
                        }
                        _ => {
                            // Unexpected op inside painter - stop painter
                            break;
                        }
                    }
                }
            }
            Op::PainterRect { .. }
            | Op::PainterCircle { .. }
            | Op::PainterLine { .. }
            | Op::PainterText { .. }
            | Op::PainterRectStroke { .. }
            | Op::PainterCircleStroke { .. }
            | Op::PainterCubicBezier { .. }
            | Op::PainterEnd => {
                // These should be consumed within PainterBegin; skip to avoid infinite loop
                *idx += 1;
            }
        }
    }
}
