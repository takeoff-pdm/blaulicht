"""Make the plan-aware copies of viz/club.js without touching it.

    python3 audio-model/melody/decision/build_club.py

club_plan.js  club.js + a small decision layer: a validated plan (plan.py) replaces the rules' choices of
              palette, look per segment, speed, leading colour and strobe treatment per drop. No plan on
              a song means exactly the rules. Fixture drawing, timing, strobe windows and the darkness
              rule are club.js's own code, so a plan cannot reach them.
core.cjs      the pure part (prepare .. showAt) for node, for the structure dump and the rule checks.

Every patch must match exactly once, so a change in club.js stops this script rather than silently
dropping a patch.
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "viz/club.js"

APPLY_PLAN = r"""// The decision layer (audio-model/melody/decision): a validated plan replaces the rules' choices and
// nothing else. palette: index into PAIRS; seg[i]: {anim, speed (-1 slower, 0, +1 faster), lead (0|1)} per
// entry of P.segStarts; hook: {hook id: anim}; drop[i]: {type, beats, rate}, where beats can only shorten
// the rule's strobe length (the low end must hold) and rate is flashes per beat (2 or 4).
function applyPlan(P, plan) {
  P.plan = plan || null;
  if (!plan) return;
  if (plan.palette != null) P.palette = { ...PAIRS[plan.palette], minor: P.palette.minor };
  if (plan.seg) { P.segAnim = plan.seg.map((s) => s.anim); P.planLead = plan.seg.map((s) => s.lead || 0); }
  if (plan.seg) { P.hookAnim = []; for (const [id, anim] of Object.entries(plan.hook || {})) P.hookAnim[+id] = anim; }
  if (plan.drop) P.drops = P.drops.map((d, i) => { const q = plan.drop[i] || {}; return { ...d, strobeType: q.type || d.strobeType, strobeBeats: Math.min(d.strobeBeats, q.beats || 4), strobeRate: q.rate || 4 }; });
}
"""

PATCHES = [
    ("  applyCues(P, song.cues || {});\n  return P;", "  applyCues(P, song.cues || {});\n  applyPlan(P, song.plan);\n  return P;"),
    ("// the strongest recent pulse of a set (decaying over `decay` per second), 0 without one\n",
     APPLY_PLAN + "// the strongest recent pulse of a set (decaying over `decay` per second), 0 without one\n"),
    ('  if (kind === "Drop") period = Math.max(1, period / 2);\n',
     '  if (kind === "Drop") period = Math.max(1, period / 2);\n'
     "  if (P.plan && P.plan.seg) { const sp = (P.plan.seg[seg] || {}).speed || 0; period = Math.max(1, Math.min(8, sp > 0 ? period / 2 : sp < 0 ? period * 2 : period)); }\n"),
    ('const strobeType = strobing ? prev.strobeType : null, perBeat = 4;', 'const strobeType = strobing ? prev.strobeType : null, perBeat = strobing ? (prev.strobeRate || 4) : 4;'),
    ("look = (S.hook >= 0 ? S.hook : S.part >= 0 ? S.part : S.seg) + S.rootLead;",
     "look = (S.hook >= 0 ? S.hook : S.part >= 0 ? S.part : S.seg) + S.rootLead + (P.planLead ? P.planLead[S.seg] || 0 : 0);"),
]


def main():
    src = SRC.read_text()
    for old, new in PATCHES:
        if src.count(old) != 1:
            raise SystemExit(f"club.js changed: patch target found {src.count(old)} times: {old[:60]!r}")
        src = src.replace(old, new)
    (HERE / "club_plan.js").write_text("// GENERATED by decision/build_club.py from viz/club.js; edit the patches there.\n" + src)
    a = src.index("// Music helpers")
    a = src.rindex("// ---", 0, a)
    b = src.index("// Scene: a 10 m wide")
    b = src.rindex("// ---", 0, b)
    core = ('"use strict";\n// GENERATED by decision/build_club.py from viz/club.js: the pure show logic, for node.\n'
            'const opts = { strobes: true, smoke: "both" };\n' + src[a:b] +
            "\nmodule.exports = { prepare, showAt, beatPos, beatTime, PAIRS, keyPalette, parseKey, opts };\n")
    (HERE / "core.cjs").write_text(core)
    print("wrote club_plan.js, core.cjs")


if __name__ == "__main__":
    main()
